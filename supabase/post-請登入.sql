■ 怎麼登入

右上角按「登入」，用 LINE 授權。第一次會請你從名冊裡點自己是誰，
點過一次之後就認得你了，以後不用再選。

■ 登入前後差在哪

沒登入看得到　　姓名、組別、班級幹部、課表、行事曆、選課時間、師資、學程辦公室
登入後才看得到　同學的公司職稱與產業、一句話自介、我可以提供、我想找、
　　　　　　　　聯絡方式，以及設成班內限定的公告、活動、資源交流與相簿

