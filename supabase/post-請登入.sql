■ 資料是你自己決定要不要公開的

公司和職稱是從新生名冊預先帶進來的，但那是大家填給學校的，
不等於同意公開在班級看板上。所以在你自己登入儲存過一次以前，
那些欄位對其他同學一律不顯示。

每一個欄位都可以單獨設定給誰看，三個選項：

　公開　　　　任何人都看得到，包含沒登入的訪客
　本屆同學　　只有登入的第十屆同學看得到（預設）
　只有自己　　誰都看不到，只有你自己編輯時看得到

不想露出的就設「只有自己」，不會有人知道你填了什麼。
