$body$看板現在只放得出大家的姓名，其餘一律要本人登入、自己決定要開放什麼。
所以你不登入，別人在名冊上看到的就只有你的名字。

■ 怎麼登入

右上角按「登入」，用 LINE 授權。第一次會請你從名冊裡點自己是誰，
點過一次之後就認得你了，以後不用再選。

■ 登入前後差在哪

沒登入看得到　　姓名、組別、班級幹部、課表、行事曆、選課時間、師資、學程辦公室
登入後才看得到　同學的公司職稱與產業、一句話自介、我可以提供、我想找、
　　　　　　　　聯絡方式，以及設成班內限定的公告、活動、資源交流與相簿

活動報名也要登入才按得到。

■ 資料是你自己決定要不要公開的

公司和職稱是從新生名冊預先帶進來的，但那是大家填給學校的，
不等於同意公開在班級看板上。所以在你自己登入儲存過一次以前，
那些欄位對其他同學一律不顯示。

每一個欄位都可以單獨設定給誰看，三個選項：

　公開　　　　任何人都看得到，包含沒登入的訪客
　本屆同學　　只有登入的第十屆同學看得到（預設）
　只有自己　　誰都看不到，只有你自己編輯時看得到

不想露出的就設「只有自己」，不會有人知道你填了什麼。
手機、Email、LINE ID 也是一樣，你想給誰看就給誰看。

■ 最想拜託大家填的兩欄

「我可以提供」和「我想找」。

我們這班橫跨開發、營造、建築、估價、地政、公部門、工程顧問、
室內裝修、資訊、能源 —— 十幾個行業。這是這個班最值錢的地方，
但如果大家都不寫，誰手上有什麼就永遠只有自己知道。

填完之後到「資源交流」開一則需求試試看。
放在 LINE 群裡問，訊息很快就被洗掉；放在看板上會留著，
而且看得到最後是誰接住的。

